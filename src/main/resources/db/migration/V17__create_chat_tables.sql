-- ---------------------------------------------------------------------
-- CHAT_ROOM (학교당 하나. 학교 ID를 그대로 PK로 쓴다)
-- ---------------------------------------------------------------------
CREATE TABLE chat_room (
                           university_id    BIGINT        NOT NULL,
                           university_name  VARCHAR(100)  NOT NULL,
                           last_content     VARCHAR(200),
                           last_content_at  TIMESTAMPTZ,
                           created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
                           updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
                           CONSTRAINT pk_chat_room PRIMARY KEY (university_id),
                           CONSTRAINT fk_chat_room_university FOREIGN KEY (university_id) REFERENCES university (id) ON DELETE RESTRICT,
    -- 마지막 메시지 내용과 시각은 같이 채워지고 같이 비어 있다
                           CONSTRAINT ck_chat_room_last_content_pair CHECK ((last_content IS NULL) = (last_content_at IS NULL))
);
COMMENT ON TABLE chat_room IS '학교 채팅방과 마지막 메시지 요약';

CREATE TRIGGER trg_chat_room_updated_at
    BEFORE UPDATE ON chat_room
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 이미 있는 학교마다 채팅방을 만들어 둔다. 이후에 추가되는 학교는 앱이 만든다
INSERT INTO chat_room (university_id, university_name)
SELECT id, name
FROM university;


-- ---------------------------------------------------------------------
-- ALLIANCE_CHAT_ROOM (연합당 하나. 연합 ID를 그대로 PK로 쓴다)
-- ---------------------------------------------------------------------
CREATE TABLE alliance_chat_room (
                                    alliance_id      BIGINT        NOT NULL,
                                    alliance_name    VARCHAR(50)   NOT NULL,
                                    last_content     VARCHAR(200),
                                    last_content_at  TIMESTAMPTZ,
                                    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
                                    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
                                    CONSTRAINT pk_alliance_chat_room PRIMARY KEY (alliance_id),
                                    CONSTRAINT fk_alliance_chat_room_alliance FOREIGN KEY (alliance_id) REFERENCES alliance (id) ON DELETE RESTRICT,
    -- 마지막 메시지 내용과 시각은 같이 채워지고 같이 비어 있다
                                    CONSTRAINT ck_alliance_chat_room_last_content_pair CHECK ((last_content IS NULL) = (last_content_at IS NULL))
);
COMMENT ON TABLE alliance_chat_room IS '연합 채팅방과 마지막 메시지 요약';

CREATE TRIGGER trg_alliance_chat_room_updated_at
    BEFORE UPDATE ON alliance_chat_room
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 이미 있는 연합(삭제되지 않은 것)마다 채팅방을 만들어 둔다. 이후에 만들어지는 연합은 앱이 만든다
INSERT INTO alliance_chat_room (alliance_id, alliance_name)
SELECT id, name
FROM alliance
WHERE deleted_at IS NULL;

-- ---------------------------------------------------------------------
-- CHAT_MESSAGE (보관 기간이 지나면 스케줄러가 hard delete)
-- ---------------------------------------------------------------------
CREATE TABLE chat_message (
                              id               BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    -- 학교 방이면 chat_room_id, 연합 방이면 alliance_chat_room_id 하나만 채운다
                              chat_room_id           BIGINT,
                              alliance_chat_room_id  BIGINT,
                              user_id          BIGINT        NOT NULL,
    -- 보낸 시점의 학교 이름과 닉네임을 남긴다 (나중에 바뀌어도 메시지는 그대로 보인다)
                              university_name  VARCHAR(100)  NOT NULL,
                              nickname         VARCHAR(30)   NOT NULL,
                              content          VARCHAR(200)  NOT NULL,
                              created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
                              updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
                              CONSTRAINT pk_chat_message PRIMARY KEY (id),
                              CONSTRAINT fk_chat_message_chat_room FOREIGN KEY (chat_room_id) REFERENCES chat_room (university_id) ON DELETE RESTRICT,
                              CONSTRAINT fk_chat_message_alliance_chat_room FOREIGN KEY (alliance_chat_room_id) REFERENCES alliance_chat_room (alliance_id) ON DELETE RESTRICT,
                              CONSTRAINT fk_chat_message_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
                              CONSTRAINT ck_chat_message_one_room CHECK (num_nonnulls(chat_room_id, alliance_chat_room_id) = 1),
    -- ChatMessageService.MAX_CONTENT_LENGTH(200)와 같다
                              CONSTRAINT ck_chat_message_content_length CHECK (char_length(content) BETWEEN 1 AND 200)
);
COMMENT ON TABLE chat_message IS '학교·연합 채팅 메시지';

-- 이전 메시지 커서 조회: WHERE chat_room_id = ? AND id < ? ORDER BY id DESC (연합 방은 alliance_chat_room_id)
-- 방 종류마다 그 방의 행만 담는 부분 인덱스를 둔다
CREATE INDEX idx_chat_message_room_id_desc ON chat_message (chat_room_id, id DESC) WHERE chat_room_id IS NOT NULL;
CREATE INDEX idx_chat_message_alliance_room_id_desc ON chat_message (alliance_chat_room_id, id DESC) WHERE alliance_chat_room_id IS NOT NULL;
-- 보관 기간 삭제: WHERE created_at < ?
CREATE INDEX idx_chat_message_created_at ON chat_message (created_at);

CREATE TRIGGER trg_chat_message_updated_at
    BEFORE UPDATE ON chat_message
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
